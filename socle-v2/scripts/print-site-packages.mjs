import { readFileSync } from 'node:fs';
import { hashPackage } from './package-hash.mjs';
const origins=JSON.parse(readFileSync('socle-v2/site-origins.json','utf8'));
for(const [site,item] of Object.entries(origins.sites)){
  const result=hashPackage(item.root);
  console.log(`SITE_RUNTIME_PACKAGE ${site} ${result.sha256} ${result.files.length} expected=${item.candidatePackageSha256}`);
}
